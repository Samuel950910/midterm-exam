! 程式用途：讀入正整數 N，用 do 迴圈計算 1 + 2 + ... + N 並輸出（Fortran 中 ! 之後到行尾都是註解）
! 【語法】program 名稱：宣告主程式開始，名稱 sum_to_n 須與最後的 end program 一致
program sum_to_n
  ! 【語法】implicit none：關閉隱式型別（否則 i～n 開頭的變數會自動當整數），所有變數都必須明確宣告，可避免打錯字
  implicit none
  ! 【用途】宣告 n（上限 N）、i（迴圈計數）、total（累加總和）
  ! 【語法】integer(kind=8) 是 8 位元組整數，最大約 9.2×10^18；:: 後面列出變數名稱，用逗號分隔
  integer(kind=8) :: n, i, total

  ! 【用途】在螢幕顯示提示文字，請使用者輸入 N
  ! 【語法】write(*,'(A)')：* 代表輸出到螢幕，'(A)' 格式表示輸出字串；advance='no' 讓游標停在同一行不換行
  write(*,'(A)', advance='no') 'Enter N: '
  ! 【用途】從鍵盤讀入使用者輸入的 N
  ! 【語法】read(*,*)：第一個 * 代表從鍵盤讀取，第二個 * 代表自由格式（自動判斷數字）
  read(*,*) n

  ! 【用途】檢查輸入是否合法：N 必須至少為 1
  ! 【語法】if (條件) then … end if：條件為真時才執行區塊內的敘述；< 是「小於」比較運算子
  if (n < 1) then
    ! 【用途】輸入不合法時顯示錯誤訊息
    ! 【語法】'(A)' 格式輸出一個字串，輸出後自動換行
    write(*,'(A)') 'Error: N must be a positive integer.'
    ! 【用途】立即結束程式，不再往下計算
    ! 【語法】stop 1：停止執行並回傳結束代碼 1（非 0 代表發生錯誤）
    stop 1
  ! 【語法】end if：結束上面的 if 區塊
  end if

  ! 【用途】累加前先把總和設為 0
  ! 【語法】= 是指定（賦值）運算，把右邊的值存進左邊的變數
  total = 0
  ! 【用途】讓 i 依序取 1、2、3、…、n，每個值各執行一次迴圈內容
  ! 【語法】do 變數 = 起始值, 結束值：計數迴圈，每次自動加 1，直到超過結束值為止
  do i = 1, n
    ! 【用途】把目前的 i 加進總和
    ! 【語法】先計算右邊 total + i，再把結果存回 total（累加的寫法）
    total = total + i
  ! 【語法】end do：結束 do 迴圈，程式會回到 do 那一行繼續下一輪
  end do

  ! 【用途】輸出結果，例如「Sum of 1 to 10 = 55」
  ! 【語法】格式 '(A,I0,A,I0)'：A 輸出字串，I0 輸出整數且不留多餘空白；後面四個項目依序對應這四個格式
  write(*,'(A,I0,A,I0)') 'Sum of 1 to ', n, ' = ', total
! 【語法】end program 名稱：主程式結束
end program sum_to_n
